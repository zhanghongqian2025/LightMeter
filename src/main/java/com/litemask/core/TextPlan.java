package com.litemask.core;

import java.util.ArrayList;
import java.util.List;

/**
 * 一个文档的「全文」与「单元分组」——两样东西，缺一不可。
 *
 * <p><b>全文</b>（{@code fullText}）：整篇拼起来的文本，给分配器扫既有占位符用
 * （原文里本来就有 {@code <身份证3>} 时不能撞号）。
 *
 * <p><b>单元分组</b>（{@code groups}）：<b>脱敏时真正喂给会话的那些文本</b>，
 * 按 zip 部件分组，组内按文档顺序。
 * 跨单元续接靠「当前喂进去的文本 == 单元序列里的第 N 个」来对齐；
 * 对不上就整体关掉续接（宁可漏脱也不错配）。
 *
 * <p><b>为什么必须是两样，不能合成一样</b>（2026-10-20 真实踩过）：
 * 全文里往往还含<b>元数据</b>（工作表名、定义名称、批注、附件名），
 * 而那些走的是<b>隐藏路径</b>——改内容但不喂编号路径。
 * 若它们也进了单元序列，序号就与实际喂进去的文本错位 →
 * 对齐失败 → <b>整个文档的续接被静默关掉</b> → 被切断的身份证碎片原样留在交付物里。
 * 当时的单元序列由「全文按 {@code '\n'} 切」得到，而 zip 里
 * {@code xl/workbook.xml} 排在工作表前面时，工作表名就是第 0 个单元，
 * 于是第一个喂进去的单元格文本对不上 → 续接整个关掉。
 *
 * <p><b>单元序列也不能由全文按 {@code '\n'} 切得到</b>：
 * 单元文本里若自带换行符（生成器把多行文本直接写进 {@code <w:t>}），
 * 一个单元会被切成两个 → 同样错位 → 同样静默关掉续接（而且是<b>整篇文档</b>都失效）。
 *
 * <p>→ 所以单元序列由 redactor <b>显式声明</b>：它就是「编号路径真正喂进去的文本」。
 *
 * <p><b>为什么按 zip 部件分组</b>（块 15）：
 * 续接的前提是「两段本来就该是连着的」。同一个部件里的相邻段落满足这个前提
 * （上一句接着下一句）；<b>不同部件之间不满足</b>——页眉里的编号与正文第一句
 * 在文件里挨着，在语义上却是两件事。
 * 合成一组时会把它们拼成一个「看起来像身份证」的串：
 * 页眉末尾 17 位数字 + 正文开头的字母 X 恰好凑成一个校验位正确的身份证号，
 * 于是两段都被按身份证脱敏——<b>误判 + 标签错</b>（用户看到的类型与原文语义无关）。
 * 分组把「可以连着」的边界显式说出来：<b>组内可以续接，组间一律不续接</b>。
 * PDF 侧早就这么做了（一个内容流 = 一组），这里让 OOXML 侧跟上。
 *
 * @param fullText 整篇文本（含元数据），给分配器扫既有占位符
 * @param groups   单元分组：每组是一个 zip 部件的单元序列，组内按脱敏顺序
 */
public record TextPlan(String fullText, List<List<String>> groups) {

    public TextPlan {
        groups = groups == null ? List.of() : List.copyOf(groups);
    }

    /**
     * 把所有分组的单元按顺序拍平成一条序列——<b>组间边界在这里丢失</b>。
     *
     * <p><b>续接绝不能用它</b>：拍平之后所有部件又变成「整篇一组」，
     * 跨部件的假续接会回来（页眉末尾的编号与正文开头的字母被拼成身份证）。
     * 它存在的唯一理由是让「分组真的在起作用」这件事<b>可以被反向验证</b>：
     * 对照实验把 {@code plan.groups()} 换成 {@code List.of(plan.units())}
     * 就等于退回块 13 的整篇一组，那条变异必须变红。
     *
     * <p>空单元不在这里去掉：去掉空单元是 {@link CrossUnitContinuation#compact} 的职责，
     * 而覆盖计算与对齐计算必须用<b>同一份</b>压实实现（见那里的说明）。
     */
    public List<String> units() {
        List<String> out = new ArrayList<>();
        for (List<String> group : groups) {
            if (group != null) {
                out.addAll(group);
            }
        }
        return List.copyOf(out);
    }
}
