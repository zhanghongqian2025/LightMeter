package com.litemask.core;

import java.util.List;

/**
 * 非正则的实体来源（目前只有本地 NER）。
 *
 * <p><b>为什么要在 core 里定义这个接口，而不是让 core 直接依赖 ner 包</b>：
 * 依赖方向必须从外向内。{@code core} 是脱敏引擎，不该知道「onnxruntime」「字符表」
 * 这些推理侧的东西；一旦 core 引用了 ner，就再也做不了不加载模型的纯正则脱敏，
 * 而且每加一个模型相关改动都要动引擎。
 *
 * <p>返回值就是 {@link Match}——NER 结果与正则命中在这里汇合成同一种东西，
 * 于是**重叠消解、出现编号、排除、替换**这四步只有一份实现。
 *
 * <p><b>为什么必须是同一份实现</b>：NER 命中和正则命中会互相重叠
 * （「北京某某科技有限公司」里若有规则命中「北京」）。如果 AI 走的是另一条替换路径，
 * 就会出现「两段各自替换、偏移互相踩」，症状是正文里少字或多字而报告一切正常。
 */
public interface EntitySource {

    /** 来源名，出现在异常信息与诊断里。 */
    String name();

    /**
     * 识别一段文本里的实体。
     *
     * <p>返回的 {@link Match} <b>不要求</b>已经排过序、编过号：
     * {@link RedactionEngine} 会统一做这两件事。
     *
     * @param text 非空文本
     * @return 命中列表；没有命中返回空列表（<b>不要返回 null</b>）
     * @throws RuntimeException 识别失败时抛出。引擎<b>不会</b>吞掉它：
     *                          静默返回空列表等于「这段没有实体」，也就是少脱。
     */
    List<Match> collect(String text);

    /**
     * 这个来源<b>此刻</b>是不是真的在工作。
     *
     * <p><b>为什么需要它</b>：本机模型可以<b>在服务运行期间被装上</b>
     * （用户在界面上点「安装模型」）。于是「来源列表非空」不等于
     * 「模型真的参与了这次脱敏」——列表里那个来源可能正因为模型还没装好
     * 而什么都没认出来。
     *
     * <p>而这两件事在用户眼里差着一整个量级：
     * 「模型参与了，0 命中」与「模型根本没参与」，
     * 前者说明这份文档确实没有人名，后者说明<b>这份文档没脱干净</b>。
     * 界面上「0 处」与「没脱干净」长得一模一样，
     * 所以引擎必须能<b>如实区分</b>这两者。
     *
     * <p>默认实现返回 {@code true}：固定存在的来源（不随运行期变化）就是一直在工作。
     *
     * @return 真的在工作就 true
     */
    default boolean isActive() {
        return true;
    }
}
