# ---------- 校验位实现（与 Java 侧互为独立实现） ----------
ID_W = [7, 9, 10, 5, 8, 4, 2, 1, 6, 3, 7, 9, 10, 5, 8, 4, 2]
ID_C = "10X98765432"


def id17(p17: str) -> str:
    return p17 + ID_C[sum(int(d) * w for d, w in zip(p17, ID_W)) % 11]


CC = "0123456789ABCDEFGHJKLMNPQRTUWXY"
CC_W = [1, 3, 9, 27, 19, 26, 16, 17, 20, 29, 25, 13, 8, 24, 10, 30, 28]


def uscc(p17: str) -> str:
    assert len(p17) == 17, p17
    bad = [c for c in p17 if c not in CC]
    assert not bad, f"前缀含被排除字符 {bad}: {p17}"
    return p17 + CC[(31 - (sum(CC.index(c) * w for c, w in zip(p17, CC_W)) % 31)) % 31]


def luhn_check(p: str) -> str:
    s, d = 0, True
    for ch in reversed(p):
        n = int(ch)
        if d:
            n *= 2
            if n > 9:
                n -= 9
        s += n
        d = not d
    return str((10 - s % 10) % 10)


def luhn_ok(s: str) -> bool:
    return luhn_check(s[:-1]) == s[-1]


def card(p: str) -> str:
    c = p + luhn_check(p)
    assert luhn_ok(c)
    return c


def flip(s: str, idx: int) -> str:
    """把某位换成一个不同的字符，制造校验不过的样本。idx 支持负数（-1 = 末位）。"""
    if idx < 0:
        idx += len(s)
    if not 0 <= idx < len(s):
        raise IndexError(f"索引 {idx} 越界，长度 {len(s)}: {s}")
    old = s[idx]
    new = "0" if old != "0" else "1"
    return s[:idx] + new + s[idx + 1:]


